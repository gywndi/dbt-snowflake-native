-- DBT_APP의 DB 수준 CREATE SCHEMA 없이 dbt를 돌리기 위한 준비. 관리자 연결(ACCOUNTADMIN)로 실행한다.
-- 모델 결과 스키마(DBT_DEV.NATIVE_TEST)를 관리자가 미리 만들고, DBT_APP에는 FUTURE SCHEMAS grant로 스키마 안의 권한만 준다.
-- 범위를 NATIVE_TEST 하나로 좁히려면 아래 grant의 "ALL/FUTURE SCHEMAS IN DATABASE DBT_DEV"를 "SCHEMA DBT_DEV.NATIVE_TEST"로 바꾼다.

USE ROLE ACCOUNTADMIN;

-- 이미 있는 스키마에 권한을 준다
GRANT USAGE ON ALL SCHEMAS IN DATABASE DBT_DEV TO ROLE DBT_APP;

GRANT CREATE VIEW, CREATE TABLE, CREATE DYNAMIC TABLE ON ALL SCHEMAS IN DATABASE DBT_DEV TO ROLE DBT_APP;

-- 앞으로 만드는 스키마에는 생성 즉시 자동으로 권한이 붙는다
GRANT USAGE ON FUTURE SCHEMAS IN DATABASE DBT_DEV TO ROLE DBT_APP;

GRANT CREATE VIEW, CREATE TABLE, CREATE DYNAMIC TABLE ON FUTURE SCHEMAS IN DATABASE DBT_DEV TO ROLE DBT_APP;

-- 관리자가 소유하는 결과 스키마를 만든다 (FUTURE grant가 먼저 있어야 DBT_APP 권한이 자동으로 붙는다)
CREATE SCHEMA IF NOT EXISTS DBT_DEV.NATIVE_TEST;

-- 확인: NATIVE_TEST의 권한 목록
SHOW GRANTS ON SCHEMA DBT_DEV.NATIVE_TEST;
